#[derive(Clone, Debug, PartialEq)]
pub enum Token {
    Let,
    Fn,
    If,
    Else,
    While,
    Return,
    True,
    False,
    Identifier(String),
    Number(f64),
    String(String),
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Semicolon,
    Assign,
    EqEqual,
    BangEqual,
    LessThan,
    LessThanOrEqual,
    GreaterThan,
    GreaterThanOrEqual,
    Plus,
    Minus,
    Star,
    Slash,
    Eof,
}
